const test = require("node:test")
const assert = require("node:assert/strict")
const { load } = require("./lib/earth-source.cjs")
const { worldCoverTile } = load("open-imagery.js")
test("WorldCover uses the advertised bounded Web Mercator pyramid", () => {
  const url = new URL(worldCoverTile(12, 1205, 1540))
  assert.equal(url.hostname, "wmts.terrascope.be")
  assert.equal(url.searchParams.get("LAYER"), "esa-worldcover-s2rgbnir-10m-2021-v2_tcc")
  assert.equal(url.searchParams.get("TIME"), "2021-01-01")
  assert.equal(url.searchParams.get("TILECOL"), "1205")
  assert.equal(url.searchParams.get("TILEROW"), "1540")
  assert.ok(worldCoverTile(8, 75, 96))
  assert.ok(worldCoverTile(14, 4823, 6160))
  for (const [z, x, y] of [[7, 1, 1], [15, 1, 1], [12, -1, 1], [12, 4096, 1], [12, 1, 0], [12, 1, 4095]])
    assert.equal(worldCoverTile(z, x, y), undefined)
})
test("Swissimage bounds match the published product extent and zooms", () => {
  const { swissImageTile, sources } = load("open-imagery.js")
  assert.equal(sources.__proto__, undefined)
  assert.match(swissImageTile(16, 34322, 22949), /swissimage-product\/default\/current\/3857\/16\/34322\/22949\.png$/)
  assert.ok(swissImageTile(8, 134, 89))
  assert.ok(swissImageTile(20, 549152, 367184))
  assert.equal(swissImageTile(14, 8299, 5636), undefined)
  assert.equal(swissImageTile(7, 67, 44), undefined)
  assert.equal(swissImageTile(21, 1, 1), undefined)
})

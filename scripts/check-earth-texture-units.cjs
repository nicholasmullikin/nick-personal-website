// Force low advertised fragment-sampler budgets and reflect the actual linked
// programs. The driver can support more than the budget, so gl.getError alone
// cannot detect the failure a small device would have.
const assert = require("node:assert/strict")
const { chromium, firefox } = require("playwright")
const {
  previewURL,
  installProbe,
  browserErrors,
  reportFailure,
} = require("./lib/earth-browser.cjs")

async function test(browser, limit) {
  const page = await browser.newPage({ viewport: { width: 640, height: 400 } })
  try {
    await installProbe(page)
    await page.addInitScript(limit => {
      for (const api of [
        window.WebGLRenderingContext,
        window.WebGL2RenderingContext,
      ]) {
        if (!api) continue
        const read = api.prototype.getParameter
        api.prototype.getParameter = function (parameter) {
          const value = read.call(this, parameter)
          return parameter === this.MAX_TEXTURE_IMAGE_UNITS
            ? Math.min(value, limit)
            : value
        }
      }
    }, limit)
    const errors = browserErrors(page)
    await page.route(/mapbox\.(satellite|terrain-rgb)\//, route =>
      route.fulfill({
        status: 404,
        headers: { "Access-Control-Allow-Origin": "*" },
        body: "No tile",
      }),
    )
    await page.route("**/tile.openstreetmap.org/**", route =>
      route.fulfill({
        status: 404,
        headers: { "Access-Control-Allow-Origin": "*" },
        body: "No tile",
      }),
    )
    const url = new URL("/harp/rendering_globe-atmosphere.html", previewURL)
    url.searchParams.set("mapbox_token", "local-sampler-test")
    await page.goto(url.href, { waitUntil: "domcontentloaded" })
    await page.waitForFunction(
      () => window.probe?.map?.earth?.environment.status.noiseReady,
    )
    await page.evaluate(() => {
      const map = window.probe.map
      map.earth.buildings.setEnabled(false)
      map.lookAt({
        target: { latitude: 34.41, longitude: -119.848 },
        distance: 750,
        tilt: 69,
        heading: 320,
      })
      window.compiledSamplerNames = () => {
        const gl = map.renderer.getContext()
        const terrain = map.visibleTileSet.dataSourceTileList.find(
          row => row.dataSource.name === "terrain",
        )
        for (const tile of terrain?.renderedTiles.values() || [])
          for (const mesh of tile.objects) {
            const mat = mesh.material
            if (!mat?.userData.earthTerrain || mat.userData.openSea) continue
            const program =
              map.renderer.properties.get(mat).currentProgram?.program
            if (!program || !gl.getProgramParameter(program, gl.LINK_STATUS))
              continue
            return Array.from(
              { length: gl.getProgramParameter(program, gl.ACTIVE_UNIFORMS) },
              (_, index) => gl.getActiveUniform(program, index),
            )
              .filter(uniform => uniform.type === gl.SAMPLER_2D)
              .map(uniform => uniform.name)
          }
      }
    })
    for (const mode of ["a", "b", "reference"]) {
      await page.evaluate(mode => {
        // Check errors generated by this draw, independently of startup
        // while Chromium may be recovering its graphics context.
        const map = window.probe.map
        map.renderer.getContext().getError()
        map.earth.setMode(mode)
        window.samplerFrame = map.frameNumber
        map.update()
      }, mode)
      await page.waitForFunction(mode => {
        const names = window.compiledSamplerNames()
        if (window.probe.map.frameNumber <= window.samplerFrame || !names)
          return false
        return mode === "a"
          ? names.includes("transmittanceLut")
          : !names.includes("transmittanceLut") &&
              names.includes("referenceMap") === (mode === "reference")
      }, mode)
      const result = await page.evaluate(() => ({
        names: window.compiledSamplerNames(),
        error: window.probe.map.renderer.getContext().getError(),
      }))
      assert.ok(
        result.names.length <= limit,
        `${mode}: ${result.names.length} fragment samplers exceed ${limit}`,
      )
      assert.equal(result.error, 0)
      console.log(
        JSON.stringify({ limit, mode, samplers: result.names.length }),
      )
    }
    assert.deepEqual(errors, [])
  } finally {
    await page.close()
  }
}
async function main() {
  const legacy = process.env.EARTH_SAMPLER_BROWSER === "firefox"
  const browser = legacy
    ? await firefox.launch({
        firefoxUserPrefs: { "webgl.enable-webgl2": false },
      })
    : await chromium.launch()
  try {
    for (const limit of [8, 9, 12, 16, 32]) await test(browser, limit)
  } finally {
    await browser.close()
  }
}
main().catch(reportFailure)
